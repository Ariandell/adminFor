create or replace function anglica_private.daily_quest_progress(
  p_user uuid,p_kind text,p_course uuid,p_starts timestamptz,p_ends timestamptz
) returns integer language plpgsql stable set search_path='' as $$
declare total integer;
begin
  case p_kind
    when 'active_minutes' then
      select coalesce(sum(active_ms)/60000,0)::integer into total from anglica_private.daily_active_time
      where user_id=p_user and activity_day=(p_starts at time zone 'Europe/Kyiv')::date;
    when 'quiz_questions_answered' then
      select count(*) into total from anglica_private.daily_question_attempts a join public.lessons l on l.id=a.lesson_id
      where a.user_id=p_user and a.received_at>=p_starts and a.received_at<p_ends
        and (p_course is null or l.course_id=p_course);
    when 'perfect_quizzes' then
      select count(*) into total from (
        select a.lesson_id,a.block_id from anglica_private.daily_question_attempts a join public.lessons l on l.id=a.lesson_id
        where a.user_id=p_user and a.received_at>=p_starts and a.received_at<p_ends
          and (p_course is null or l.course_id=p_course)
          and a.content_revision=md5(jsonb_build_object('blocks',l.content->'blocks','introduction',l.content->'introduction')::text)
        group by a.lesson_id,a.block_id,l.content
        having bool_and(a.result='correct') and count(*)=(select count(*) from anglica_private.daily_block_questions(l.content,a.block_id))
      ) completed;
    when 'audio_listened' then
      select count(*) into total from anglica_private.daily_audio_progress a join public.lessons l on l.id=a.lesson_id
      where a.user_id=p_user and a.completed_at>=p_starts and a.completed_at<p_ends
        and (p_course is null or l.course_id=p_course);
    when 'ai_tasks_completed' then
      select count(*) into total from anglica_private.daily_ai_successes a join public.lessons l on l.id=a.lesson_id
      where a.user_id=p_user and a.received_at>=p_starts and a.received_at<p_ends
        and (p_course is null or l.course_id=p_course);
    when 'correct_answers_streak' then
      select coalesce(max(run_count),0)::integer into total from (
        select count(*) filter(where result='correct' and (p_course is null or course_id=p_course)) run_count
        from (
          select a.result,l.course_id,sum(case when a.result='incorrect' then 1 else 0 end) over(order by a.id) run_id
          from anglica_private.daily_question_attempts a join public.lessons l on l.id=a.lesson_id
          where a.user_id=p_user and a.received_at>=p_starts and a.received_at<p_ends
        ) runs group by run_id
      ) longest;
    else return anglica_private.daily_quest_progress_v2_core(p_user,p_kind,p_course,p_starts,p_ends);
  end case;
  return coalesce(total,0);
end;
$$;
revoke all on function anglica_private.daily_quest_progress(uuid,text,uuid,timestamptz,timestamptz) from public,anon,authenticated;

create or replace function anglica_private.daily_quest_capacity(
  p_user uuid,p_kind text,p_course uuid,p_starts timestamptz,p_ends timestamptz
) returns integer language plpgsql stable set search_path='' as $$
declare total integer; tail_count integer;
begin
  case p_kind
    when 'active_minutes' then return 120;
    when 'quiz_questions_answered' then
      select count(*) into total from anglica_private.daily_course_lessons(p_user,p_course) l
      join public.lessons source on source.id=l.lesson_id
      cross join lateral anglica_private.daily_quiz_questions(source.content) q
      where public.learning_can_open(l.lesson_id) and q.question->>'type' in ('single_choice','multiple_choice','text_input','matching','ordering')
        and (select count(*) from anglica_private.daily_quiz_questions(source.content) duplicate where duplicate.answer_key=q.answer_key)=1;
    when 'correct_answers_streak' then
      select count(*) into total from anglica_private.daily_course_lessons(p_user,p_course) l
      join public.lessons source on source.id=l.lesson_id
      cross join lateral anglica_private.daily_quiz_questions(source.content) q
      where public.learning_can_open(l.lesson_id) and anglica_private.daily_question_gradable(q.question)
        and (select count(*) from anglica_private.daily_quiz_questions(source.content) duplicate where duplicate.answer_key=q.answer_key)=1
        and not exists(select 1 from anglica_private.daily_question_attempts a where a.user_id=p_user
          and a.lesson_id=l.lesson_id and a.question_key=q.answer_key and a.received_at>=p_starts and a.received_at<p_ends);
      select count(*) into tail_count from anglica_private.daily_question_attempts a join public.lessons l on l.id=a.lesson_id
      where a.user_id=p_user and a.received_at>=p_starts and a.received_at<p_ends
        and a.result='correct' and (p_course is null or l.course_id=p_course)
        and a.id>coalesce((select max(previous.id) from anglica_private.daily_question_attempts previous
          where previous.user_id=p_user and previous.received_at>=p_starts and previous.received_at<p_ends and previous.result='incorrect'),0);
      total:=greatest(total+tail_count,anglica_private.daily_quest_progress(p_user,p_kind,p_course,p_starts,p_ends));
    when 'perfect_quizzes' then
      select count(*) into total from anglica_private.daily_course_lessons(p_user,p_course) l
      join public.lessons source on source.id=l.lesson_id
      cross join lateral anglica_private.daily_blocks(source.content) b
      where public.learning_can_open(l.lesson_id) and b.block->>'type'='quiz'
        and (select count(*) from anglica_private.daily_blocks(source.content) duplicate where duplicate.block_id=b.block_id)=1
        and not exists(select 1 from anglica_private.daily_question_attempts a where a.user_id=p_user
          and a.lesson_id=l.lesson_id and a.block_id=b.block_id and a.received_at>=p_starts and a.received_at<p_ends and a.result<>'correct')
        and exists(select 1 from anglica_private.daily_block_questions(source.content,b.block_id) q
          having count(*)>0 and bool_and(anglica_private.daily_question_gradable(q.question)) and count(*)=count(distinct q.answer_key));
    when 'audio_listened' then
      select count(*) into total from anglica_private.daily_course_lessons(p_user,p_course) l
      join public.lessons source on source.id=l.lesson_id
      cross join lateral anglica_private.daily_blocks(source.content) b
      where public.learning_can_open(l.lesson_id) and b.block->>'type'='audio' and coalesce(b.block->'data'->>'url','') ~ '^https://'
        and (select count(*) from anglica_private.daily_blocks(source.content) duplicate where duplicate.block_id=b.block_id)=1;
    when 'ai_tasks_completed' then
      select count(*) into total from anglica_private.daily_course_lessons(p_user,p_course) l
      join public.lessons source on source.id=l.lesson_id
      cross join lateral anglica_private.daily_blocks(source.content) b
      where public.learning_can_open(l.lesson_id) and b.block->>'type'='aiBlock'
        and jsonb_typeof(b.block->'id')='string' and b.block->>'id'=b.block_id
        and (select count(*) from anglica_private.daily_blocks(source.content) duplicate where duplicate.block_id=b.block_id)=1
        and length(trim(coalesce(b.block->'data'->>'question','')))>0
        and length(trim(coalesce(b.block->'data'->>'evaluationPrompt','')))>0;
    else return anglica_private.daily_quest_capacity_v2_core(p_user,p_kind,p_course,p_starts,p_ends);
  end case;
  return coalesce(total,0);
end;
$$;
revoke all on function anglica_private.daily_quest_capacity(uuid,text,uuid,timestamptz,timestamptz) from public,anon,authenticated;

create or replace function anglica_private.daily_today_version(p_version integer)
returns jsonb language plpgsql volatile security definer set search_path='' as $$
declare
  p_expanded boolean := p_version>=2;
  learner uuid := (select auth.uid());
  today date := (now() at time zone 'Europe/Kyiv')::date;
  day_start timestamptz := today::timestamp at time zone 'Europe/Kyiv';
  day_end timestamptz := (today+1)::timestamp at time zone 'Europe/Kyiv';
  legacy_kinds text[] := array['lessons_completed','cards_reviewed','weak_words'];
  allowed_kinds text[]:=case when p_version=1 then legacy_kinds else array['lessons_completed','cards_reviewed','weak_words',
    'courses_practiced','course_finished','quiz_lessons_checked','cards_known','weak_words_known','personal_cards_reviewed','personal_words_added']
    ||case when p_version>=3 then array['active_minutes','quiz_questions_answered','perfect_quizzes','audio_listened','ai_tasks_completed','correct_answers_streak']
      else '{}'::text[] end end;
  starts timestamptz; ends timestamptz; q record; total integer; next_slot integer; scope uuid;
  issued_expanded boolean;
  assigned_kinds text[];
begin
  if learner is null or not exists(select 1 from auth.users where id=learner and email_confirmed_at is not null)
    then raise exception 'authentication_required' using errcode='42501'; end if;
  perform pg_advisory_xact_lock(hashtextextended('daily/'||learner::text||'/'||today::text,0));
  select coalesce(max(slot),0),coalesce(bool_or(case when p_version>=3 then activity_issued else expanded_issued end),false),coalesce(array_agg(kind),'{}'::text[])
    into next_slot,issued_expanded,assigned_kinds
    from anglica_private.daily_assignments where user_id=learner and quest_day=today;
  -- Keep issued slots across clients. The first expanded fetch may fill space
  -- left by the legacy client, but never replaces an already issued quest.
  if next_slot<3 and (next_slot=0 or (p_expanded and not issued_expanded)) then
    for q in select * from public.daily_quest_templates where is_active
      and kind=any(allowed_kinds) and (not p_expanded or not kind=any(assigned_kinds))
      order by case when p_expanded then row_number() over (partition by kind
        order by md5(learner::text||today::text||id::text)) else 1 end,
        md5(learner::text||today::text||id::text) limit 200 loop
      if p_expanded and q.kind=any(assigned_kinds) then continue; end if;
      scope:=q.course_id;
      if q.kind='course_finished' then
        -- The last lesson must be possible today. Pin the chosen course in the
        -- assignment even when the template allows any eligible course.
        select l.course_id into scope from anglica_private.daily_course_lessons(learner,scope) l
        group by l.course_id
        having (count(*) filter (where l.first_completed_at is null)=1
          and bool_or(l.first_completed_at is null and public.learning_can_open(l.lesson_id)))
          or (count(*)=count(l.first_completed_at)
            and max(l.first_completed_at)>=day_start and max(l.first_completed_at)<day_end)
        order by md5(today::text||l.course_id::text) limit 1;
        if scope is null then continue; end if;
      elsif anglica_private.daily_quest_capacity(learner,q.kind,scope,day_start,day_end)<q.target then
        continue;
      end if;
      next_slot:=next_slot+1;
      insert into anglica_private.daily_assignments(user_id,quest_day,slot,template_id,title,description,kind,target,reward_points,course_id)
        values(learner,today,next_slot,q.id,q.title,q.description,q.kind,q.target,q.reward_points,scope);
      assigned_kinds:=array_append(assigned_kinds,q.kind);
      exit when next_slot=3;
    end loop;
  end if;
  if p_expanded and not issued_expanded and next_slot>0 then
    update anglica_private.daily_assignments set expanded_issued=true,activity_issued=activity_issued or p_version>=3 where user_id=learner and quest_day=today;
  end if;

  for q in select * from anglica_private.daily_assignments where user_id=learner
    and quest_day between today-7 and today and awarded_at is null
    and kind=any(allowed_kinds) loop
    starts:=q.quest_day::timestamp at time zone 'Europe/Kyiv';
    ends:=(q.quest_day+1)::timestamp at time zone 'Europe/Kyiv';
    total:=anglica_private.daily_quest_progress(learner,q.kind,q.course_id,starts,ends);
    update anglica_private.daily_assignments set progress=greatest(progress,least(q.target,total)),
      awarded_at=case when total>=q.target then least(now(),ends-interval '1 microsecond') end
      where user_id=learner and quest_day=q.quest_day and slot=q.slot;
  end loop;

  return jsonb_build_object('day',today,'resetsAt',day_end,'serverNow',now(),
    'quests',coalesce((select jsonb_agg(jsonb_build_object('id',template_id,'title',title,'description',description,
      'kind',kind,'target',target,'reward',reward_points,'courseId',course_id,'progress',progress,'completed',awarded_at is not null,
      'wordKeys',case when a.kind in ('weak_words','weak_words_known') then coalesce((select jsonb_agg(k.word_key) from (
        select wk.word_key from anglica_private.daily_word_keys(learner,a.course_id) wk
        where exists(select 1 from public.user_word_practice_events old where old.user_id=learner
          and old.word_key=wk.word_key and old.kind='incorrect' and old.received_at<day_start)
        order by md5(today::text||wk.word_key) limit 100
      ) k),'[]'::jsonb) else '[]'::jsonb end) ||
      case when p_expanded then jsonb_build_object('destination',case
        when a.kind='active_minutes' then 'home'
        when a.kind in ('lessons_completed','courses_practiced','course_finished','quiz_lessons_checked',
          'quiz_questions_answered','perfect_quizzes','audio_listened','ai_tasks_completed','correct_answers_streak') then 'lessons'
        when a.kind in ('personal_cards_reviewed','personal_words_added') then 'personal_words'
        else 'words' end) else '{}'::jsonb end order by slot)
      from anglica_private.daily_assignments a where user_id=learner and quest_day=today
        and kind=any(allowed_kinds)),'[]'::jsonb));
end;
$$;
revoke all on function anglica_private.daily_today_version(integer) from public,anon,authenticated;

