create or replace function anglica_private.daily_blocks(p_content jsonb)
returns table(block_id text,block jsonb) language sql immutable set search_path='' as $$
  select case when jsonb_typeof(b.value->'id')='string' and b.value->>'id'<>'' then b.value->>'id'
    else 'block-'||((row_number() over(order by b.ordinality))-1)::text end,b.value
  from jsonb_array_elements(case when jsonb_typeof(p_content->'blocks')='array'
    then p_content->'blocks' else '[]'::jsonb end) with ordinality b
  where jsonb_typeof(b.value)='object';
$$;
revoke all on function anglica_private.daily_blocks(jsonb) from public,anon,authenticated;

create or replace function anglica_private.daily_block_questions(p_content jsonb,p_block_id text)
returns table(answer_key text,question jsonb) language sql immutable set search_path='' as $$
  select b.block_id||'/'||case when jsonb_typeof(q.value->'id')='string' and q.value->>'id'<>''
    then q.value->>'id' else q.position end,q.value
  from anglica_private.daily_blocks(p_content) b
  cross join lateral (
    select x.value,(row_number() over(order by x.ordinality)-1)::text position
    from jsonb_array_elements(case when jsonb_typeof(b.block->'data'->'questions')='array'
      then b.block->'data'->'questions' else '[]' end) with ordinality x
    where jsonb_typeof(x.value)='object'
  ) q where b.block_id=p_block_id and b.block->>'type'='quiz';
$$;
revoke all on function anglica_private.daily_block_questions(jsonb,text) from public,anon,authenticated;

create or replace function anglica_private.daily_normalize_answer(p_text text,p_sensitive boolean default false)
returns text language sql immutable set search_path='' as $$
  select case when p_sensitive then normalized else lower(normalized) end
  from (select regexp_replace(trim(replace(replace(coalesce(p_text,''),'’',chr(39)),'‘',chr(39))),'\s+',' ','g') normalized) clean;
$$;
revoke all on function anglica_private.daily_normalize_answer(text,boolean) from public,anon,authenticated;

-- Mirrors Exercise.evaluate. Autobiographical all-valid choices remain personal.
create or replace function anglica_private.daily_question_result(p_question jsonb,p_answer jsonb)
returns text language plpgsql immutable set search_path='' as $$
declare
  qtype text:=p_question->>'type'; options jsonb; expected jsonb; selected jsonb;
  option_count integer; expected_count integer; chosen_count integer; correct boolean;
begin
  if not anglica_private.daily_quiz_answered(p_question,p_answer) then return 'unavailable'; end if;
  case qtype
    when 'single_choice' then
      select count(*) into option_count from jsonb_array_elements(coalesce(p_question->'answers','[]')) value where jsonb_typeof(value)='object';
      if jsonb_typeof(p_question->'correctAnswerIndex') is distinct from 'number' or not (p_question->>'correctAnswerIndex') ~ '^[0-9]+$'
        or (p_question->>'correctAnswerIndex')::numeric>=option_count then return 'unavailable'; end if;
      correct:=p_answer=p_question->'correctAnswerIndex';
    when 'text_input' then
      options:=case when jsonb_typeof(p_question->'correctAnswers')='array' then p_question->'correctAnswers' else '[]' end;
      if not exists(select 1 from jsonb_array_elements(options) a where jsonb_typeof(a->'value')='string' and trim(a->>'value')<>'') then return 'unavailable'; end if;
      select exists(select 1 from jsonb_array_elements(options) a where jsonb_typeof(a->'value')='string' and trim(a->>'value')<>''
        and anglica_private.daily_normalize_answer(a->>'value',p_question->'caseSensitive'='true'::jsonb)
          =anglica_private.daily_normalize_answer(p_answer #>> '{}',p_question->'caseSensitive'='true'::jsonb)) into correct;
    when 'multiple_choice' then
      options:=case when jsonb_typeof(p_question->'answers')='array' then p_question->'answers' else '[]' end;
      select count(*) into option_count from jsonb_array_elements(options) a where jsonb_typeof(a)='object';
      expected:=case when jsonb_typeof(p_question->'correctAnswers')='array' then p_question->'correctAnswers' else '[]' end;
      if jsonb_array_length(expected)=0 or exists(select 1 from jsonb_array_elements(expected) a
        where case when jsonb_typeof(a)='number' and (a#>>'{}') ~ '^[0-9]+$' then (a#>>'{}')::numeric>=option_count else true end) then return 'unavailable'; end if;
      select count(distinct a) into expected_count from jsonb_array_elements(expected) a;
      select count(distinct a) into chosen_count from jsonb_array_elements(p_answer) a;
      if expected_count=option_count and chosen_count>0 then return 'personal'; end if;
      correct:=expected_count=chosen_count and expected @> p_answer and p_answer @> expected;
    when 'ordering' then
      options:=case when jsonb_typeof(p_question->'items')='array' then p_question->'items' else '[]' end;
      select count(*),count(distinct a->'order') into option_count,expected_count from jsonb_array_elements(options) a where jsonb_typeof(a)='object';
      if option_count=0 or option_count<>expected_count or exists(select 1 from jsonb_array_elements(options) a
        where jsonb_typeof(a)='object' and jsonb_typeof(a->'order') is distinct from 'number') then return 'unavailable'; end if;
      select jsonb_agg(position order by (a->>'order')::numeric) into expected from (
        select a, (row_number() over(order by ordinal)-1)::integer position
        from jsonb_array_elements(options) with ordinality x(a,ordinal) where jsonb_typeof(a)='object'
      ) ordered;
      correct:=p_answer=expected;
    when 'matching' then
      options:=case when jsonb_typeof(p_question->'pairs')='array' then p_question->'pairs' else '[]' end;
      select jsonb_agg(a order by ordinal) into selected from jsonb_array_elements(options) with ordinality x(a,ordinal) where jsonb_typeof(a)='object';
      if selected is null or exists(select 1 from jsonb_array_elements(selected) a where jsonb_typeof(a->'right') is distinct from 'string' or trim(a->>'right')='') then return 'unavailable'; end if;
      select bool_and(trim((selected->(ordinal::integer-1))->>'right')=trim((selected->(a#>>'{}')::integer)->>'right'))
        into correct from jsonb_array_elements(p_answer) with ordinality x(a,ordinal);
    else return 'unavailable';
  end case;
  return case when coalesce(correct,false) then 'correct' else 'incorrect' end;
end;
$$;
revoke all on function anglica_private.daily_question_result(jsonb,jsonb) from public,anon,authenticated;

create or replace function anglica_private.daily_question_gradable(p_question jsonb)
returns boolean language plpgsql immutable set search_path='' as $$
declare candidate jsonb;
begin
  case p_question->>'type'
    when 'single_choice' then candidate:=p_question->'correctAnswerIndex';
    when 'multiple_choice' then candidate:=p_question->'correctAnswers';
    when 'text_input' then
      select a->'value' into candidate from jsonb_array_elements(case when jsonb_typeof(p_question->'correctAnswers')='array'
        then p_question->'correctAnswers' else '[]' end) a where jsonb_typeof(a->'value')='string' and trim(a->>'value')<>'' limit 1;
    when 'ordering' then
      select jsonb_agg(position order by (a->>'order')::numeric) into candidate from (
        select a,(row_number() over(order by ordinal)-1)::integer position
        from jsonb_array_elements(case when jsonb_typeof(p_question->'items')='array' then p_question->'items' else '[]' end)
          with ordinality x(a,ordinal) where jsonb_typeof(a)='object'
      ) items where jsonb_typeof(a->'order')='number';
    when 'matching' then
      select coalesce(jsonb_agg(position),'[]') into candidate from (
        select (row_number() over(order by ordinal)-1)::integer position
        from jsonb_array_elements(case when jsonb_typeof(p_question->'pairs')='array' then p_question->'pairs' else '[]' end)
          with ordinality x(a,ordinal) where jsonb_typeof(a)='object'
      ) pairs;
    else return false;
  end case;
  return anglica_private.daily_question_result(p_question,candidate)='correct';
end;
$$;
revoke all on function anglica_private.daily_question_gradable(jsonb) from public,anon,authenticated;

create or replace function public.daily_activity_sync(p_events jsonb)
returns jsonb language plpgsql volatile security definer set search_path='' as $$
declare
  learner uuid:=(select auth.uid()); stamp timestamptz:=statement_timestamp();
  today date:=(statement_timestamp() at time zone 'Europe/Kyiv')::date;
  event jsonb; v_event_id uuid; v_lesson uuid; course uuid; content jsonb; revision text; question jsonb; block jsonb;
  v_block text; v_question_key text; kind text; elapsed bigint; claimed bigint; duration bigint; credited bigint;
  previous timestamptz; inserted integer; accepted jsonb:='[]'; rejected jsonb:='[]';
begin
  if learner is null or not exists(select 1 from auth.users where id=learner and email_confirmed_at is not null) then
    raise exception 'authentication_required' using errcode='42501'; end if;
  if jsonb_typeof(p_events) is distinct from 'array' or jsonb_array_length(p_events)>50 or octet_length(p_events::text)>65536 then
    raise exception 'invalid_activity_batch' using errcode='22023'; end if;
  perform pg_advisory_xact_lock(hashtextextended('daily/activity/'||learner::text,0));
  insert into anglica_private.daily_activity_clock(user_id) values(learner) on conflict do nothing;
  if exists(select 1 from anglica_private.daily_activity_clock where user_id=learner
    and (last_cleanup_day is null or last_cleanup_day<today)) then
    delete from anglica_private.daily_activity_receipts where user_id=learner and received_at<stamp-interval '8 days';
    delete from anglica_private.daily_question_attempts where user_id=learner and activity_day<today-8;
    delete from anglica_private.daily_audio_progress where user_id=learner and activity_day<today-8;
    delete from anglica_private.daily_active_time where user_id=learner and activity_day<today-8;
    delete from anglica_private.daily_ai_successes where user_id=learner and activity_day<today-8;
    update anglica_private.daily_activity_clock set last_cleanup_day=today where user_id=learner;
  end if;
  for event in select value from jsonb_array_elements(p_events) loop
    begin
      if jsonb_typeof(event)<>'object' or coalesce(event->>'id','') !~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' then
        raise exception 'invalid_activity_event' using errcode='22023'; end if;
      v_event_id:=(event->>'id')::uuid; kind:=event->>'kind';
      if exists(select 1 from anglica_private.daily_activity_receipts r where r.user_id=learner and r.event_id=v_event_id) then
        accepted:=accepted||jsonb_build_array(v_event_id); continue; end if;
      if kind='active' then
        if jsonb_typeof(event->'activeMs') is distinct from 'number' or not (event->>'activeMs') ~ '^[0-9]+$' then
          raise exception 'invalid_active_duration' using errcode='22023'; end if;
        claimed:=least((event->>'activeMs')::numeric,30000)::bigint;
        select active_at into previous from anglica_private.daily_activity_clock where user_id=learner;
        elapsed:=case when previous is not null and previous>=stamp-interval '60 seconds'
          then greatest(0,floor(extract(epoch from stamp-greatest(previous,today::timestamp at time zone 'Europe/Kyiv'))*1000)) else 0 end;
        credited:=least(claimed,elapsed,30000);
        update anglica_private.daily_activity_clock set active_at=stamp where user_id=learner;
        insert into anglica_private.daily_active_time(user_id,activity_day,active_ms) values(learner,today,credited)
          on conflict(user_id,activity_day) do update set active_ms=least(86400000,daily_active_time.active_ms+excluded.active_ms);
      elsif kind in ('quiz_answer','audio') then
        if coalesce(event->>'lessonId','') !~ '^[0-9a-fA-F-]{36}$' or length(coalesce(event->>'blockId','')) not between 1 and 240 then
          raise exception 'invalid_activity_task' using errcode='22023'; end if;
        v_lesson:=(event->>'lessonId')::uuid; v_block:=event->>'blockId';
        if not public.learning_can_open(v_lesson) then raise exception 'lesson_unavailable' using errcode='42501'; end if;
        select l.content,l.course_id,md5(jsonb_build_object('blocks',l.content->'blocks','introduction',l.content->'introduction')::text)
          into content,course,revision from public.lessons l where l.id=v_lesson;
        if (select count(*) from anglica_private.daily_blocks(content) b where b.block_id=v_block)<>1 then
          raise exception 'ambiguous_activity_task' using errcode='22023'; end if;
        select b.block into block from anglica_private.daily_blocks(content) b where b.block_id=v_block;
        if block is null then raise exception 'task_unavailable' using errcode='22023'; end if;
        if kind='quiz_answer' then
          v_question_key:=event->>'questionKey';
          if block->>'type'<>'quiz' or event->>'contentRevision' is distinct from revision
            or length(coalesce(v_question_key,'')) not between 1 and 481
            or left(v_question_key,length(v_block)+1)<>v_block||'/' then
            raise exception 'question_unavailable' using errcode='22023'; end if;
          if (select count(*) from anglica_private.daily_quiz_questions(content) q where q.answer_key=v_question_key)<>1 then
            raise exception 'ambiguous_activity_question' using errcode='22023'; end if;
          select q.question into question from anglica_private.daily_block_questions(content,v_block) q where q.answer_key=v_question_key;
          if question is null or not anglica_private.daily_quiz_answered(question,event->'answer') then
            raise exception 'invalid_question_answer' using errcode='22023'; end if;
          insert into anglica_private.daily_question_attempts(user_id,activity_day,lesson_id,block_id,question_key,content_revision,result)
            values(learner,today,v_lesson,v_block,v_question_key,revision,anglica_private.daily_question_result(question,event->'answer'))
            on conflict(user_id,activity_day,lesson_id,question_key) do nothing;
        else
          if block->>'type'<>'audio' or coalesce(block->'data'->>'url','') !~ '^https://' or
            jsonb_typeof(event->'playedMs') is distinct from 'number' or not (event->>'playedMs') ~ '^[0-9]+$' or
            jsonb_typeof(event->'durationMs') is distinct from 'number' or not (event->>'durationMs') ~ '^[0-9]+$' then
            raise exception 'invalid_audio_segment' using errcode='22023'; end if;
          duration:=case when jsonb_typeof(block->'data'->'durationMs')='number' and (block->'data'->>'durationMs') ~ '^[0-9]+$'
            then (block->'data'->>'durationMs')::numeric else (event->>'durationMs')::numeric end;
          if duration not between 1000 and 1800000 then raise exception 'invalid_audio_duration' using errcode='22023'; end if;
          claimed:=least((event->>'playedMs')::numeric,37500)::bigint;
          select audio_at into previous from anglica_private.daily_activity_clock where user_id=learner;
          select greatest(previous,a.last_received_at) into previous from anglica_private.daily_audio_progress a
            where a.user_id=learner and a.activity_day=today and a.lesson_id=v_lesson and a.block_id=v_block;
          elapsed:=case when previous is not null and previous>=stamp-interval '60 seconds'
            then greatest(0,floor(extract(epoch from stamp-previous)*1250)) else 0 end;
          credited:=least(claimed,elapsed,37500);
          update anglica_private.daily_activity_clock set audio_at=stamp where user_id=learner;
          insert into anglica_private.daily_audio_progress(user_id,activity_day,lesson_id,block_id,duration_ms,played_ms,last_received_at)
            values(learner,today,v_lesson,v_block,duration,credited,stamp)
            on conflict(user_id,activity_day,lesson_id,block_id) do update set
              duration_ms=greatest(daily_audio_progress.duration_ms,excluded.duration_ms),
              played_ms=least(1800000,daily_audio_progress.played_ms+excluded.played_ms),last_received_at=stamp;
          update anglica_private.daily_audio_progress a set completed_at=stamp
            where a.user_id=learner and a.activity_day=today and a.lesson_id=v_lesson and a.block_id=v_block
              and a.completed_at is null and a.played_ms>=a.duration_ms*.9;
        end if;
      else raise exception 'unsupported_activity_kind' using errcode='22023';
      end if;
      insert into anglica_private.daily_activity_receipts(user_id,event_id) values(learner,v_event_id);
      accepted:=accepted||jsonb_build_array(v_event_id);
    exception when invalid_parameter_value or invalid_text_representation or numeric_value_out_of_range or insufficient_privilege then
      rejected:=rejected||jsonb_build_array(event->>'id');
    end;
  end loop;
  return jsonb_build_object('accepted',accepted,'rejected',rejected,'serverNow',stamp);
end;
$$;
revoke all on function public.daily_activity_sync(jsonb) from public,anon;
grant execute on function public.daily_activity_sync(jsonb) to authenticated;

-- Only an already authenticated provider handler can write AI success receipts.
create or replace function public.record_daily_ai_success(p_user_id uuid,p_lesson_id uuid,p_block_id text,p_request_id text)
returns boolean language plpgsql volatile security definer set search_path='' as $$
declare previous_sub text:=current_setting('request.jwt.claim.sub',true); content jsonb; allowed boolean;
begin
  if p_user_id is null or length(coalesce(p_block_id,'')) not between 1 and 240
    or length(coalesce(p_request_id,'')) not between 1 and 240
    or not exists(select 1 from auth.users where id=p_user_id and email_confirmed_at is not null) then return false; end if;
  perform set_config('request.jwt.claim.sub',p_user_id::text,true);
  allowed:=public.learning_can_open(p_lesson_id);
  perform set_config('request.jwt.claim.sub',coalesce(previous_sub,''),true);
  if not allowed then return false; end if;
  select l.content into content from public.lessons l where l.id=p_lesson_id;
  if (select count(*) from anglica_private.daily_blocks(content) b where b.block_id=p_block_id)<>1 then return false; end if;
  if not exists(select 1 from anglica_private.daily_blocks(content) b
    where b.block_id=p_block_id and b.block->>'type'='aiBlock'
      and jsonb_typeof(b.block->'id')='string' and b.block->>'id'=p_block_id
      and length(trim(coalesce(b.block->'data'->>'question','')))>0
      and length(trim(coalesce(b.block->'data'->>'evaluationPrompt','')))>0) then return false; end if;
  insert into anglica_private.daily_ai_successes(user_id,activity_day,lesson_id,block_id)
    values(p_user_id,(statement_timestamp() at time zone 'Europe/Kyiv')::date,p_lesson_id,p_block_id)
    on conflict do nothing;
  return true;
end;
$$;
